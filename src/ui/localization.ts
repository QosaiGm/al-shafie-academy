export function translateText(value: string, language: Language): string {
  const leading = value.match(/^\s*/)?.[0] ?? ''
  const trailing = value.match(/\s*$/)?.[0] ?? ''
  const key = value.trim()
  if (!key) return value
  const translated = language === 'en'
    ? translations[key] ?? translateDynamic(key, language)
    : englishToArabic.get(key) ?? translateDynamic(key, language)
  return translated ? `${leading}${translated}${trailing}` : value
}

function translateAttributes(element: Element, language: Language) {
  for (const attribute of ['placeholder', 'title', 'aria-label']) {
    const value = element.getAttribute(attribute)
    if (!value) continue
    const translated = translateText(value, language)
    if (translated !== value) element.setAttribute(attribute, translated)
  }
}

function translateNode(node: Node, language: Language) {
  if (node.nodeType === Node.TEXT_NODE) {
    const value = node.nodeValue ?? ''
    const translated = translateText(value, language)
    if (translated !== value) node.nodeValue = translated
    return
  }
  if (!(node instanceof Element) || node.closest('[data-no-translate]')) return
  translateAttributes(node, language)
  for (const child of Array.from(node.childNodes)) translateNode(child, language)
}

export function localizeDom(root: Node, language: Language) {
  translateNode(root, language)
}

export function formatLocale(): string {
  return document.documentElement.lang === 'en' ? 'en-PS' : 'ar-PS'
}
